import Foundation

public enum DeviceIdentifierTable: Sendable {
    public static let mapping: [String: String] = [

"""

let entries = sortedKeys.map { key -> String in
    let escapedVal = table[key]!.replacingOccurrences(of: "\"", with: "\\\"")
    return "        \"\(key)\": \"\(escapedVal)\""
}

output += entries.joined(separator: ",\n")
output += "\n"

output += """
    ]

    public static func lookup(_ identifier: String) -> String? {
        mapping[identifier]
    }
}
"""
output += "\n"

let destination = URL(fileURLWithPath: "CruftlessCore/Sources/CruftlessCore/Naming/DeviceIdentifierTable.swift")
