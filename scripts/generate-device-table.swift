#!/usr/bin/env swift
import Foundation

var table: [String: String] = [:]

// Scans local CoreSimulator profiles.
let profilesURL = URL(fileURLWithPath: "/Library/Developer/CoreSimulator/Profiles/DeviceTypes")
if let bundles = try? FileManager.default.contentsOfDirectory(at: profilesURL, includingPropertiesForKeys: nil) {
    for bundle in bundles where bundle.pathExtension == "simdevicetype" {
        let profilePlistURL = bundle.appendingPathComponent("Contents/Resources/profile.plist")
        let infoPlistURL = bundle.appendingPathComponent("Contents/Info.plist")

        var marketingName: String? = if let infoData = try? Data(contentsOf: infoPlistURL),
                                        let infoPlist = try? PropertyListSerialization.propertyList(
                                            from: infoData,
                                            options: [],
                                            format: nil
                                        ) as? [String: Any],
                                        let name = infoPlist["CFBundleName"] as? String {
            name
        } else {
            bundle.deletingPathExtension().lastPathComponent
        }

        if let profileData = try? Data(contentsOf: profilePlistURL),
           let profilePlist = try? PropertyListSerialization.propertyList(from: profileData, options: [], format: nil) as? [String: Any],
           let modelID = profilePlist["modelIdentifier"] as? String,
           let name = marketingName {
            table[modelID] = name
        }
    }
}

